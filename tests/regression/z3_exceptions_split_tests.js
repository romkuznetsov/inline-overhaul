/* ---------- 1. таблица в docs/dev/Z3_EXCEPTIONS.md ---------- */

const rowRe = /^\|\s*(\d+)\s*\|([^|]*)\|([^|]*)\|/gm;
const rows = [];
for (let m = rowRe.exec(z3doc); m; m = rowRe.exec(z3doc)) {
  rows.push({ n: Number(m[1]), date: m[2].trim(), files: m[3].trim() });
}

assert.strictEqual(
  rows.length,
  ORDINALS.length,
  "в таблице исключений " + rows.length + " строк, а исключений " + ORDINALS.length +
    ": таблицу и этот список правят одним заходом"
);

rows.forEach((row, i) => {
  assert.strictEqual(row.n, i + 1, "номера в таблице идут не подряд: " + row.n);
  assert.match(
    row.date,
    /20\d\d-\d\d-\d\d/,
    "у строки " + row.n + " в таблице нет даты: " + JSON.stringify(row.date)
  );
  assert.match(
    row.files,
    /`[\w./-]+\.(?:js|ts|mjs)`/,
    "у строки " + row.n + " в таблице не назван файл: " + JSON.stringify(row.files)
  );
});

/* ---------- 2. абзацы в PRD 3.3 ---------- */

const secStart = prd.indexOf("### 3.3 Запреты");
assert.ok(secStart > 0, "раздел 3.3 в PRD не найден");
const secEnd = prd.indexOf("\n## ", secStart);
assert.ok(secEnd > secStart, "конец раздела 3.3 в PRD не найден");
const section = prd.slice(secStart, secEnd);

/* Нарезка по пометкам «Исключение …» / «Исключения …, … и …». Границей служит
   следующая пометка, а у последней — конец раздела: без этой границы абзац
   тридцать пятого тянулся бы до конца файла и «содержал» бы любое имя. */
const markRe = /\*\*Исключени[ея][^*]*\*\*/g;
const marks = [];
for (let m = markRe.exec(section); m; m = markRe.exec(section)) {
  marks.push({ at: m.index, text: m[0] });
}
assert.ok(marks.length >= 20, "пометок «Исключение …» в PRD 3.3 слишком мало: " + marks.length);

/*
 * Числительные вкладываются друг в друга, и **не только составные**.
 *
 * Первая версия снимала с текста пометки составные («двадцать первое»), а
 * потом искала в остатке одиночные — иначе абзац двадцать первого исключения
 * достался бы первому. Признак был выбран неверно: дело не в пробеле, а в
 * длине. «Пятидесятое» — одно слово, и внутри него целиком лежит «десятое»;
 * появление пятидесятого исключения увело абзац десятого, и проверка
 * покраснела на файле, который из него никуда не девался.
 *
 * Поэтому снимаются они по убыванию длины, и всё снятое заменяется пробелом.
 */
function ordinalsIn(text) {
  let rest = text;
  const found = [];
  const byLength = ORDINALS
    .map((word, idx) => ({ word, number: idx + 1 }))
    .sort((a, b) => b.word.length - a.word.length);
  for (const row of byLength) {
    if (!rest.includes(row.word)) continue;
    found.push(row.number);
    rest = rest.split(row.word).join(" ");
  }
  return found.sort((a, b) => a - b);
}

assert.deepStrictEqual(
  ordinalsIn("**Исключение двадцать первое, разрешённое**"),
  [21],
  "разбор числительных считает «двадцать первое» ещё и первым"
);
/* Тот же контроль на вложении без пробела — им проверка и покраснела. */
assert.deepStrictEqual(
  ordinalsIn("**Исключение пятидесятое, разрешённое**"),
  [50],
  "разбор числительных считает «пятидесятое» ещё и десятым"
);

const blockOf = new Map();
marks.forEach((mark, i) => {
  const to = i + 1 < marks.length ? marks[i + 1].at : section.length;
  const body = section.slice(mark.at, to);
  for (const n of ordinalsIn(mark.text)) blockOf.set(n, body);
});

const missing = [];
for (let n = 1; n <= ORDINALS.length; n++) {
  if (!blockOf.has(n)) missing.push(n + " (" + ORDINALS[n - 1] + ")");
}
assert.deepStrictEqual(
  missing,
  [],
  "у этих исключений нет своего абзаца в PRD 3.3: " + missing.join(", ")
);

/* Положительный контроль нарезки: имя первого исключения не должно находиться
   в абзаце тридцать пятого. */
assert.ok(
  blockOf.get(1).includes("reconcileModeDependencies"),
  "нарезка PRD сломана: в абзаце первого исключения нет его функции"
);
assert.ok(
  !blockOf.get(35).includes("reconcileModeDependencies"),
  "нарезка PRD не ограничена: абзац тридцать пятого исключения содержит функцию первого"
);

/* ---------- 3. файлы строки стоят в своём абзаце ---------- */

const fileRe = /`([\w./-]+\.(?:js|ts|mjs))`/g;
const wrong = [];
let namesSeen = 0;
rows.forEach((row) => {
  const body = blockOf.get(row.n);
  const names = new Set();
  for (let m = fileRe.exec(row.files); m; m = fileRe.exec(row.files)) {
    names.add(m[1].split("/").pop());
  }
  namesSeen += names.size;
  for (const name of names) {
    if (!body.includes(name)) wrong.push(row.n + ": " + name);
  }
});
/*
 * Порог до вывода: запрет ниже зелен и тогда, когда имён файлов не извлеклось
 * ни одного — например, от смены написания таблицы. Имя у каждой строки есть
 * хотя бы одно, значит их не меньше, чем строк (У-88).
 */
assert.ok(
  namesSeen >= rows.length,
  "положительный контроль: имён файлов извлечено " + namesSeen + " при " + rows.length +
    " строках таблицы — запрет ниже мерит пустоту"
);
assert.deepStrictEqual(
  wrong,
  [],
  "файл назван в таблице, но не в абзаце своего исключения в PRD 3.3: " + wrong.join("; ")
);

/* ---------- 4. историй в CLAUDE.md больше нет ---------- */

const historyRe = /^ {2}\d+\. \*\*20\d\d-\d\d-\d\d/gm;
const back = claude.match(historyRe) || [];
assert.deepStrictEqual(
  back,
  [],
  "истории исключений снова стоят в CLAUDE.md (" + back.length + " пунктов): их дом — PRD 3.3"
);

/* ---------- 5. у таблицы один дом ---------- */

/*
 * Переезд двигает и утверждения о нём (У-94). Здесь два: копия таблицы не
 * вернулась в `CLAUDE.md`, и оттуда есть ссылка на её настоящий дом. Второе —
 * не украшение: правило, уехавшее в файл, на который никто не ссылается, это
 * правило, которого нет.
 */
const claudeRows = claude.match(/^\s*\|\s*\d+\s*\|\s*20\d\d-\d\d-\d\d/gm) || [];
assert.deepStrictEqual(
  claudeRows,
  [],
  "таблица исключений снова стоит в CLAUDE.md (" + claudeRows.length + " строк): её дом — docs/dev/Z3_EXCEPTIONS.md"
);
assert.ok(
  claude.indexOf("docs/dev/Z3_EXCEPTIONS.md") >= 0,
  "в CLAUDE.md нет ссылки на docs/dev/Z3_EXCEPTIONS.md: таблица уехала бы в файл, о котором не сказано"
);

console.log(
  "ok: исключений к З3 " + rows.length + ", у каждого строка таблицы в docs/dev/Z3_EXCEPTIONS.md и " +
    "абзац в PRD 3.3; файлы строк стоят в своих абзацах, второго дома у таблицы нет"
);

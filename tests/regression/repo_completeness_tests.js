"use strict";

/**
 * Репозиторий полон: проверка не читает того, чего в нём нет.
 *
 * **Дефект, который здесь закреплён, 2026-09-06.** `live_preview_wake_tests.ts`
 * читала копию настоящего конфига из `tests/fixtures/`, закрытую `.gitignore`
 * по маске приватных снимков. На машине, где файл лежал, все 48 проверок были
 * зелёными; в CI и на свежем клоне та же проверка падала с `ENOENT`, и падала
 * десять дней. Увидеть это своими глазами было нельзя ничем: файл есть, набор
 * зелёный, повод усомниться отсутствует.
 *
 * Поэтому сторож спрашивает не файловую систему, а **git**: это и есть разница
 * между «файл есть у меня» и «файл есть у всех».
 *
 * **Правило написано о папке, а не о тексте проверок, и это не лень.** Первая
 * версия искала в исходниках литерал `tests` + `/fixtures/` + имя — и была
 * зелёной при снятой фикстуре: путь к ней собран из кусков через `path.join`,
 * и литерала в тексте нет вовсе. Мутация это показала сразу. Папку подделать
 * нечем: что в ней лежит, то проверка и может прочитать.
 *
 * **Приватный снимок конфига в папке лежать может** — по маске из `.gitignore`,
 * его читает `tools/migration_report.js` по пути из аргумента. Нельзя другого:
 * чтобы от такого снимка зависела проверка. Это и есть второе правило.
 *
 * **Git обязателен, и его отсутствие — красный, а не пропуск.** Тихо
 * пропущенная проверка — это проверка, которой нет (У-36, У-41); а здесь тихий
 * пропуск вернул бы ровно тот дефект, ради которого сторож заведён.
 */

const assert = require("assert");
const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const root = path.resolve(__dirname, "..", "..");
const FIXTURES = path.join(root, "tests", "fixtures");

/** Маска приватных снимков — та же, что в `.gitignore`. Собрана, а не написана:
 *  литерал в этом файле поймало бы второе правило, и поймало бы законно. */
const PRIVATE_PREFIX = "data" + "_owner_";

/** Файлы под контролем версий — списком от самого git, а не разбором `.gitignore`. */
function trackedFiles() {
  let out;
  try {
    out = execFileSync("git", ["ls-files", "-z"], { cwd: root, maxBuffer: 64 * 1024 * 1024 });
  } catch (e) {
    assert.fail(
      "не удалось спросить git о списке файлов (" + String(e && e.message) + ").\n" +
      "Эта проверка отвечает на вопрос «есть ли файл у всех, а не только у меня», " +
      "и без git ответа на него нет. Пропускать её нельзя: ради этого она и написана."
    );
  }
  /* `-z` разделяет имена нулевым байтом: в путях бывают пробелы и кириллица.
     Сам байт в исходник не пишется — гейт репозитория запрещает нулевой байт. */
  const NUL = String.fromCharCode(0);
  return new Set(String(out).split(NUL).filter(Boolean).map((p) => p.replace(/\\/g, "/")));
}

const tracked = trackedFiles();
assert.ok(tracked.size > 100, "git отдал подозрительно короткий список файлов: " + tracked.size);

/* ---- правило первое: в папке фикстур нет ничего, чего нет у всех ---------- */

const inFolder = fs.readdirSync(FIXTURES, { withFileTypes: true })
  .filter((e) => e.isFile())
  .map((e) => e.name);
assert.ok(inFolder.length > 0, "папка фикстур пуста — сторожить нечего, и это само по себе странно");

const untracked = inFolder
  .filter((name) => !name.startsWith(PRIVATE_PREFIX))
  .filter((name) => !tracked.has("tests/fixtures/" + name));

assert.deepStrictEqual(
  untracked,
  [],
  "в папке фикстур лежит файл, которого нет в репозитории — у вас он есть, у CI и на свежем клоне его не будет:\n  " +
  untracked.join("\n  ") + "\n" +
  "Либо добавьте его под контроль версий, либо, если он приватный, назовите его по маске приватных снимков."
);

/* ---- правило второе: от приватного снимка не зависит ни одна проверка ----- */

function sourcesUnder(dir) {
  const found = [];
  const walk = (d) => {
    for (const entry of fs.readdirSync(d, { withFileTypes: true })) {
      const full = path.join(d, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (/\.(ts|js|mjs)$/.test(entry.name)) found.push(full);
    }
  };
  walk(dir);
  return found;
}

const sources = sourcesUnder(path.join(root, "tests"));
assert.ok(sources.length > 20, "файлов проверок нашлось подозрительно мало: " + sources.length);

const dependsOnPrivate = sources
  .filter((file) => fs.readFileSync(file, "utf8").includes(PRIVATE_PREFIX))
  .map((file) => path.relative(root, file).replace(/\\/g, "/"));

assert.deepStrictEqual(
  dependsOnPrivate,
  [],
  "проверка зависит от приватного снимка конфига, а он в репозиторий не попадает:\n  " +
  dependsOnPrivate.join("\n  ")
);

/* ---- правило третье: собранного в репозитории нет ------------------------ */

/**
 * Обратная сторона первых двух правил, и спрашивается тем же git.
 *
 * До 2026-09-06 `dist/main.js`, `dist/manifest.json` и `dist/styles.css` лежали
 * под контролем версий (A13, фаза 6 пункт 3). Это два промаха сразу: на
 * community review — замечание, а в работе — тихий источник расхождения.
 * Закоммиченная сборка живёт своей жизнью и расходится с исходником в тот
 * момент, когда кто-то поправил исходник и не пересобрал; заметить это можно
 * только сплошной сверкой, то есть никак.
 *
 * **Почему сторож, а не одна запись в `.gitignore`.** `.gitignore` молчит про
 * уже отслеживаемый файл: `git rm --cached` забыли — и всё осталось как было,
 * с зелёным набором. Спрашивать надо git, а не читать `.gitignore` (то же
 * рассуждение, что в правиле первом).
 *
 * **Корневой `main.js` сюда не входит, и это не поблажка.** Он не сборка, а
 * исходник: 6173 строки, написанные руками, с комментариями и историей правок.
 * Сборка лежит в `dist/main.js` и собирается из него же. Из репозитория он
 * уходит пунктом 2 фазы 6 — разбором на `main.ts` и модули, — а не удалением:
 * удалить исходник значило бы удалить плагин. До тех пор он назван здесь
 * поимённо, чтобы «в репозитории лежит main.js» не читалось как недосмотр.
 */
{
  const BUILT_PREFIXES = ["dist/"];
  const builtTracked = [...tracked].filter(
    (p) => BUILT_PREFIXES.some((prefix) => p.startsWith(prefix)),
  ).sort();

  assert.deepStrictEqual(
    builtTracked,
    [],
    "собранный плагин под контролем версий (A13, фаза 6 пункт 3):\n  " +
    builtTracked.join("\n  ") + "\n" +
    "Записи в `.gitignore` мало — она молчит про уже отслеживаемый файл. Нужно: git rm -r --cached dist"
  );

  /* И `.gitignore` о том же говорит: без записи папка вернётся первым же
     `git add -A`, и сторож покраснеет уже после того, как она вернулась. */
  const ignore = fs.readFileSync(path.join(root, ".gitignore"), "utf8");
  assert.ok(
    /^dist\/?$/m.test(ignore),
    "в .gitignore нет записи про dist/: сборка вернётся под контроль версий первым же `git add -A`"
  );

  /* Корневой `main.js` — исходник, и он обязан быть у всех. Утверждение
     перестанет быть верным, когда пункт 2 фазы 6 разберёт его на `main.ts`:
     тогда правится эта проверка, а не обходится. */
  assert.ok(
    tracked.has("src/main.js"),
    "корневого main.js нет под контролем версий. Если его разобрали пунктом 2 фазы 6 — " +
    "поправьте это утверждение здесь; если нет — плагин остался без исходника"
  );
}

/*
 * **Пустой файл без расширения в корне — след оболочки, а не работа.**
 *
 * 2026-09-16 текст с обратными кавычками уехал в `python -c` через двойные
 * кавычки оболочки, та выполнила содержимое кавычек как команды, и в корне
 * репозитория осталось четыре файла нулевой длины с именами из русских слов
 * (`памяти:`, `плагину:`, …). Они ушли в коммит и были бы выложены: `git add
 * -A` не спрашивает, откуда взялся файл.
 *
 * Правило, которое это нарушило, в `CLAUDE.md` стоит с 6 сентября — «текст с
 * обратными кавычками пишется инструментом правки файла, а не через оболочку
 * вообще». Правило было, сторожа не было, и признак отказа («command not
 * found» на слове из своего же текста) виден только тому, кто смотрит на
 * вывод (У-185: форма дописывается в обход вместе с починкой).
 *
 * Признак узкий нарочно: **нулевая длина** и отсутствие расширения. Законные
 * имена без расширения названы поимённо — по маске имени их не отличить.
 */
{
  const LEGAL = new Set(["LICENSE", ".gitignore", ".gitattributes"]);
  const looksLikeShellDebris = (name, size) =>
    !LEGAL.has(name) && !path.extname(name) && size === 0;

  /* Контроль до первого утверждения (У-119, У-127) — на образцах, а не на том,
     что мусор в корне ещё есть: такой контроль умер бы вместе с уборкой. */
  assert.strictEqual(looksLikeShellDebris("памяти:", 0), true,
    "положительный контроль: признак видит след оболочки");
  assert.strictEqual(looksLikeShellDebris("LICENSE", 0), false,
    "положительный контроль: законное имя без расширения следом не считается");
  assert.strictEqual(looksLikeShellDebris("README.md", 0), false,
    "положительный контроль: файл с расширением следом не считается");
  assert.strictEqual(looksLikeShellDebris("что-то", 42), false,
    "положительный контроль: непустой файл следом не считается");

  const debris = fs.readdirSync(root)
    .filter((name) => {
      const full = path.join(root, name);
      if (!fs.statSync(full).isFile()) return false;
      return looksLikeShellDebris(name, fs.statSync(full).size);
    });
  assert.deepStrictEqual(debris, [],
    "в корне лежат пустые файлы без расширения — это след подстановки обратных кавычек в " +
    "оболочке, а не работа: " + debris.map((x) => JSON.stringify(x)).join(", ") +
    "\nТекст с обратными кавычками пишется инструментом правки файла, а не через оболочку.");
}

console.log(
  "Repo completeness tests: OK (файлов в папке фикстур " + inFolder.length +
  ", все под контролем версий; проверок, зависящих от приватных снимков, нет; " +
  "собранного плагина в репозитории нет)"
);

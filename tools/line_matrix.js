/**
 * Материал для форм строки — **из его конфига и домами продукта**.
 *
 * Тег и ссылка выглядят в строке по-разному, и как именно — знает то же
 * объявление, которым их печатают движки (`buildOutputToken`, 10.13.130).
 * Своё «приставка плюс значение» здесь было бы третьим объявлением правила.
 */
function materialFor(rules) {
  const helpers = require(path.join(ROOT, "src", "core", "pkm_rules_runtime_helpers.js"));
  const core = require(path.join(ROOT, "pkm_v2", "TagWheel", "tagwheel_core.js"));
  const fields = [].concat(
    Array.isArray(rules && rules.leftMode && rules.leftMode.fields) ? rules.leftMode.fields : [],
    Array.isArray(rules && rules.rightMode && rules.rightMode.fields) ? rules.rightMode.fields : []
  );
  const firstValue = (f) => (Array.isArray(f && f.values) ? f.values : []).filter((v) => v && v.token)[0] || null;
  const tags = [];
  const known = new Set();
  let link = "";
  for (const f of fields) {
    if (!f || f.enabled === false) continue;
    if (String(f.dependsOn || "").trim()) continue;
    const v = firstValue(f);
    if (!v) continue;
    const token = String(core.buildOutputToken(f, v, rules) || "").trim();
    if (!token) continue;
    for (const val of (Array.isArray(f.values) ? f.values : [])) {
      const t = String(core.buildOutputToken(f, val, rules) || "").trim();
      if (t) known.add(t);
    }
    if (helpers.isWikilinkSourceField(f)) {
      if (!link) link = token;
      continue;
    }
    if (String(f.marker || "").trim()) continue;
    if (tags.length < 2) tags.push(token);
  }
  /*
   * Ссылка, которой нет ни в одном списке значений, — та самая, что оставляет
   * `Inline to note`. Имя перебирается до первого свободного: его значения
   * принадлежат ему и могут называться как угодно.
   */
  let foreignLink = "";
  for (let i = 0; i < 100 && !foreignLink; i++) {
    const candidate = "[[333/заметка" + i + "]]";
    if (!known.has(candidate)) foreignLink = candidate;
  }
  return { tags: tags, link: link, foreignLink: foreignLink };
}

/*
 * Правила для разбора собираются **той же функцией**, что и у движков.
 *
 * Своя сборка «разделители плюс список меток» здесь стояла и врала: без формы
 * Fields разбор не считает значение элемента значением Field, и обход объявил
 * сломанными заведомо здоровые строки вида `- 📅… || ` (У-119).
 */
function rulesOf(cfg) {
  return rulesShape.buildRulesForEngines(cfg);
}

/**
 * Неподвижность строки: разобрать и собрать заново обязано дать её же.
 *
 * Спрашивается у тех самых функций, которыми это делают движки, — своей копии
 * разбора здесь нет.
 */
function fixpointOf(line, rules) {
  const seg = linePipeline.splitSegments(line, rules);
  const again = linePipeline.buildFromSegments(seg, rules);
  return { stable: again === line, again, seg };
}


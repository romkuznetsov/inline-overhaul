"use strict";

/**
 * Ключей без читателя в `data.json` быть не должно.
 *
 * **Его заказ 2026-09-19:** «я хочу, чтобы ты проверил, что в data.json и в
 * генерируемых файлах бэкапа нет других мёртвых веток. В целом ты ранее
 * выполнял аудит кода, я ожидал, что после его завершения и выполнения всех
 * выявленных проблем подобных ситуаций не будет».
 *
 * **Почему это проверка, а не разовый обход.** Разовый ответ «сейчас чисто»
 * стареет в день, когда снимут следующую функцию: ключ останется в файле
 * человека и будет выглядеть настройкой. Мера — `node tools/dead_keys.js`, а
 * здесь она стоит сторожем на двух предметах, которые есть в репозитории:
 * конфиг умолчаний и заметка копии настроек. Файл заказчика проверяется той же
 * командой руками: его снимок в репозиторий не попадает — маска приватных
 * снимков конфига закрыта `.gitignore`, и проверка, зависящая от него, была бы
 * зелёной только у меня (У-78).
 *
 * **Контроль стоит до первого вывода** (У-119): обход обязан назвать заведомо
 * мёртвую ветку и не назвать заведомо живую. Без этого «мёртвых нет» читалось
 * бы как «обход ищет не то».
 */

const assert = require("node:assert/strict");
const path = require("node:path");

const root = path.resolve(__dirname, "..", "..");
const dead = require(path.join(root, "tools", "dead_keys.js"));
const normalize = require(path.join(root, "src", "core", "config_normalize.js"));
const backup = require(path.join(root, "src", "features", "settings_backup.js"));

let passed = 0;
function ok(label) { passed++; console.log("  ok " + label); }

const known = dead.knownPaths();

/* ---- 1. контроль обхода ------------------------------------------------- */

{
  /* Порог назван измерением: на этом дереве обход собирает 223 пути — 147 из
     схемы и остальные из рантайма. Половина от измеренного — признак «собрал
     не то», а не круглое число. */
  assert.ok(known.size > 150,
    "известных путей всего " + known.size + " — обход собрал не то, и сравнивать нечем");
  const probe = dead.sweep({
    visual: { tags: { opacityLeft: 100 } },
    zzzDeadBranch: { zzzKey: 1 },
  }, known);
  assert.deepEqual(probe, ["zzzDeadBranch.zzzKey"],
    "контроль: обход называет мёртвую ветку и не называет живую настройку: "
    + JSON.stringify(probe));
  ok("обход различает живую настройку и мёртвую ветку (" + known.size + " известных путей)");
}

/* ---- 2. конфиг умолчаний ------------------------------------------------ */

{
  /*
   * Умолчания — тот конфиг, который плагин создаёт сам на чистом vault. Если
   * в нём есть ключ без читателя, значит плагин **сам** кладёт человеку
   * ловушку.
   */
  const fresh = normalize.migrateConfig({}, { log: () => {} });
  const found = dead.sweep(fresh, known);
  assert.deepEqual(found, [],
    "плагин создаёт ключи, которых сам не читает:\n  " + found.join("\n  "));
  ok("в конфиге умолчаний ключей без читателя нет");
}

/* ---- 3. конфиг после переезда с версии 1 -------------------------------- */

{
  /*
   * Вторая сторона: файл, приехавший с версии 1. Именно так в файле заказчика
   * и оказались кеш конфиг-заметки и три листа приставок — их принёс переезд,
   * а снять их было некому.
   */
  const v1 = normalize.migrateConfig({
    schemaVersion: 1,
    pkm: {
      taxonomy: { tagWheelConfig: { sourcePath: "Old.md" } },
      /* Путь версии 1 — именно `pkm.behavior.prefixRules`: так лежало у него.
         Три листа переезжают в `pkm.prefixPriority.*`, а их близнецы на новом
         месте снимаются списком снятых ключей. */
      behavior: {
        prefixRules: {
          priorityMode: "by-checkbox-list",
          fieldsOrderMode: "auto",
          tagSubtagPriority: "tag-over-subtag",
        },
      },
    },
  }, { log: () => {} });
  const found = dead.sweep(v1, known);
  assert.deepEqual(found, [],
    "после переезда с версии 1 в файле остались ключи без читателя:\n  " + found.join("\n  "));
  ok("после переезда с версии 1 ключей без читателя тоже нет");
}

/* ---- 4. заметка копии настроек ------------------------------------------ */

{
  /*
   * **Его слово про «генерируемые файлы бэкапа».** Заметка копии несёт тот же
   * конфиг, и читает её тот же разбор: значит спрашивается то же самое — но
   * спрашивается **у написанного**, а не у того, что мы собирались написать.
   */
  const cfg = normalize.migrateConfig({}, { log: () => {} });
  const note = backup.buildBackupNote({
    config: cfg,
    parts: backup.allPartIds(),
    hotkeyScope: "own",
    hotkeys: {},
    pluginVersion: "0.0.0-test",
    savedAt: new Date(2026, 8, 19, 12, 0, 0),
  });
  const back = backup.parseBackupNote(note);
  const found = dead.sweep(back, known);
  assert.deepEqual(found, [],
    "в заметке копии лежат ключи, которых не читает никто:\n  " + found.join("\n  "));
  ok("в заметке копии настроек ключей без читателя нет");
}

console.log("\n" + passed + " проверок пройдено");

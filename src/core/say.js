"use strict";

/**
 * Видимый текст по ключу каталога — для кода, который про панель не знает
 * (PRD 10.13.50, третий кусок каталога).
 *
 * **Зачем отдельный модуль на десять строк.** Спрашивают отсюда три места:
 * `main.js` и два файла `pkm_v2/**`. Написать одно и то же в трёх — значит
 * объявить одно правило трижды и однажды разойтись молча (У-32); из такой же
 * тройки уже вырос дефект Б-11 со схемой идентификатора команды.
 *
 * **Шов — `globalThis.__inlineSay`, и ставит его слой настроек.** Так рантайм
 * получает и всё остальное: `__inlinePkmMacroShared`, `__inlineLinePipeline`,
 * `__inlineStatusLineRuntimeUnified`, а TagWheel — сам `Notice`.
 *
 * **Нет шва — есть английский.** Панели может не быть вовсе: старый Obsidian
 * или не загрузившийся модуль, и тогда `createSettingTab()` отдаёт `null`.
 * Человек в этом случае обязан увидеть сообщение, а не ключ, поэтому
 * английский литерал стоит на месте вызова вторым аргументом и никуда оттуда
 * не уезжает. Тот же контракт, что у `PLAIN` в слое настроек.
 */

/**
 * @param {string} key      ключ каталога, собранный `noticeKey`, а не литерал
 * @param {string} english  что показать, если каталога нет
 * @param {...(string|number)} args  подстановки на места `{0}`, `{1}`, …
 */
function say(key, english, ...args) {
  let text = String(english == null ? "" : english);
  try {
    const ask = globalThis.__inlineSay;
    if (typeof ask === "function") {
      const said = ask(String(key), text);
      if (typeof said === "string" && said !== "") text = said;
    }
  } catch (_) {
    /* Сообщение человеку не должно падать из-за того, что перевод не
       достался: показываем английское и идём дальше. */
  }
  /*
   * Подстановка по номеру, а не склейка через `+`: по-русски то, что
   * по-английски стоит в конце фразы, встаёт в начало, и склейка этого не
   * переживает (то же правило, что у текстов окон, 10.13.46 Р2).
   */
  return args.reduce(
    (out, value, i) => out.split("{" + i + "}").join(String(value == null ? "" : value)),
    text,
  );
}

module.exports = { say };

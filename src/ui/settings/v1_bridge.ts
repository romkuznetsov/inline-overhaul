/**
 * Мост между путями схемы и путями конфига, который читает рантайм.
 *
 * **Зачем он есть.** Схема панели выведена из прототипа и пользуется путями
 * **версии 2**. Движки читают **версию 1**: миграция `config_migration_v2`
 * написана, но не подключена — её включают в фазе 2, пункт 4, вместе с
 * переводом самих движков. До тех пор настройка, записанная по пути v2, лежит
 * в конфиге мёртвым грузом: её никто не читает.
 *
 * Это не теория. На 2026-08-29, когда старая панель была удалена, **52 из 87
 * настроек панели писали туда, куда рантайм не смотрит** — ползунки двигались,
 * значение сохранялось, и не менялось ничего. Ровно то, что запрещает З8,
 * только не на одном контроле, а на большей части панели.
 *
 * **Решение то же, что уже принято для своих блоков.** Binder (Б-8) и
 * `Color your Tags` (Ц-2) пишут версию 1 по решению заказчика: туда же, откуда
 * читает рантайм. Здесь то же самое, только для настроек схемы, и делается это
 * одним швом, а не правкой восьмидесяти семи записей: путь переводится на
 * чтении и на записи.
 *
 * **Карта одна.** Направления берутся из `ROUTES` в самой миграции — второй
 * такой карты быть не должно, она разошлась бы с первой на первой же правке.
 * Мост снимается в фазе 2 целиком: когда движки читают v2, переводить нечего.
 *
 * **Единицы.** Прозрачность в v1 — доля `0..1`, в схеме v2 — проценты
 * `0..100`. Это единственный перенос в таблице 8.1, который меняет значение, а
 * не только путь, и мост обязан переводить его в обе стороны.
 */

import { ROUTES } from "../../core/config_migration_v2.ts";

/** Куда на самом деле ходить за значением настройки схемы. */
export interface BridgedPath {
  /** Путь в конфиге, который читает рантайм. */
  path: string;
  /** Значение из конфига — в то, что показывает контрол. */
  read: (value: unknown) => unknown;
  /** Значение из контрола — в то, что кладётся в конфиг. */
  write: (value: unknown) => unknown;
}

const same = (v: unknown): unknown => v;

/** Доля `0..1` в проценты `0..100`: то же, что делает миграция. */
function shareToPercent(v: unknown): unknown {
  const n = Number(v);
  if (!Number.isFinite(n)) return v;
  const pct = Math.round(n * 100);
  return pct < 0 ? 0 : pct > 100 ? 100 : pct;
}

/** И обратно, для записи. */
function percentToShare(v: unknown): unknown {
  const n = Number(v);
  if (!Number.isFinite(n)) return v;
  const share = n / 100;
  return share < 0 ? 0 : share > 1 ? 1 : share;
}

/**
 * Обратная карта: путь схемы (v2) → путь конфига (v1).
 *
 * Берутся только **листья**: ветки, помеченные `whole`, переносятся целиком и
 * внутрь них схема не смотрит — там живут свои блоки, и они и так пишут v1.
 * Ветки с `drop` не переносятся вовсе. Маршрут, у которого путь не меняется,
 * в карту не попадает: переводить нечего.
 */
const BACK: ReadonlyMap<string, BridgedPath> = (() => {
  const out = new Map<string, BridgedPath>();
  for (const [from, route] of ROUTES) {
    if (route.drop || route.whole || route.alreadyV2) continue;
    const to = route.to;
    if (!to || to === from) continue;
    out.set(to, {
      path: from,
      /* Единицы меняет ровно один маршрут — прозрачность. */
      read: route.cast === undefined ? same : shareToPercent,
      write: route.cast === undefined ? same : percentToShare,
    });
  }
  return out;
})();

/** Сколько путей переводится. Проверка сверяет это число со схемой. */
export const bridgedCount = (): number => BACK.size;

/**
 * Куда ходить за настройкой. Путь, которого в карте нет, отдаётся как есть:
 * либо он одинаков в обеих версиях, либо это настройка, которой в v1 не было
 * вовсе (`Show tips`, `Setting ids`) — такие живут по своему пути с самого
 * начала.
 */
export function bridge(schemaPath: string): BridgedPath {
  const found = BACK.get(schemaPath);
  return found || { path: schemaPath, read: same, write: same };
}

/** Все переводимые пути: проверке нужен полный список, а не выборка. */
export function bridgedPaths(): ReadonlyMap<string, BridgedPath> {
  return BACK;
}

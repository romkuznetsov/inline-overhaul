"use strict";

/**
 * **Долг копий закреплён поимённо и умеет только убывать.**
 *
 * Его слово 2026-09-16: «в следующей сессии разбери все 23, я хочу, чтобы
 * следующая сессия стала последней по доработке этого технического долга».
 * Разобрать — мало: без сторожа долг отрастает молча, и следующая сессия
 * начинает разбор заново.
 *
 * Поэтому здесь список, а не число (У-109, У-145): каждое имя названо вместе с
 * вердиктом, полученным прогоном, и новое имя роняет проверку в том виде, в
 * каком его завели.
 *
 * **Два списка, и у них разный смысл.**
 *
 *   * `REAL` — имена, у которых два и более настоящих тела и правило в них
 *     есть. Это и есть долг. Сегодня в нём одно имя, и оно не сводится: причина
 *     написана рядом.
 *   * `NOT_A_RULE` — имена, у которых тела правила **не объявляют**: доставалки
 *     модуля и ленивая сборка своего экземпляра. Вердикт выводится из формы, и
 *     печатает её `node tools/rule_copy_shapes.js`. Список здесь затем, чтобы
 *     род нельзя было приписать чужому имени молча.
 *
 * Мера спрашивается вызовом, а не разбором её вывода: свой разборщик чужого
 * текста есть то же второе объявление правила (У-96).
 */

const assert = require("assert");
const path = require("path");

const { measure } = require(path.join(__dirname, "..", "..", "tools", "rule_copies.js"));

/** Настоящие копии: правило объявлено больше одного раза и сводится решением. */
const REAL = [
  /*
   * `applyPkmOptionKeys` — один и тот же вопрос у двух движков: «взять имена
   * ключей настроек у общего модуля и разложить по своим переменным». Сводить
   * нечего: присваивание идёт в **модульные** имена каждого файла, и наборы у
   * них разные — у движка дат шесть имён, у движка тегов восемь. Общий дом
   * отдал бы тот же объект, а строки присваивания остались бы на месте.
   * Разводить имена тоже нельзя: вопрос один, и разные имена соврали бы.
   */
  "applyPkmOptionKeys",
];

/** Не правила: вердикт выводится из формы тела. */
const NOT_A_RULE = [
  "getTransformFeature",
  "getDomainRegistry",
  "getSharedUtils",
  "getStatusRuntimeCommon",
  "getStatusLineRuntimeUnified",
  "ensureStatusRuntimeCommonLoaded",
  "__relocation",
];

function run() {
  const m = measure();

  /*
   * Положительный контроль **до** первого утверждения (У-119, У-127): мера
   * обязана хоть что-то находить. Круглый ноль здесь читался бы как «долга
   * нет», а означал бы, что обход промахнулся мимо всего рантайма.
   */
  assert.ok(m.twins.length > 20,
    "мера не нашла почти ни одного имени с двумя объявлениями (" + m.twins.length + ") — обход промахнулся");
  assert.ok(m.seen > 500,
    "мера видит подозрительно мало объявлений верхнего уровня (" + m.seen + ") — обход промахнулся");
  assert.ok(m.unseen > 0,
    "мера говорит, что вложенных и стрелочных объявлений в проекте нет — образец промахнулся");
  assert.deepStrictEqual(m.broken, [],
    "у этих объявлений не сошлись скобки — их разбирает человек: " + m.broken.join(", "));

  const real = m.real.map((t) => t.name).sort();
  const notARule = m.notRules.map((t) => t.name).sort();

  assert.deepStrictEqual(real, REAL.slice().sort(),
    "долг копий изменился. Новое имя — это второе объявление правила: сведите его или разведите имена, "
    + "а если ни то ни другое, впишите сюда вместе с причиной. Сейчас: " + real.join(", "));

  assert.deepStrictEqual(notARule, NOT_A_RULE.slice().sort(),
    "список «правила не объявляют вовсе» изменился. Вердикт выводится из формы, и печатает её "
    + "`node tools/rule_copy_shapes.js` — сверьтесь с ним, прежде чем править список. Сейчас: "
    + notARule.join(", "));

  console.log("ok: долг копий " + real.length + " (" + real.join(", ") + "); "
    + "не правил по форме " + notARule.length + "; имён с двумя объявлениями всего " + m.twins.length);
}

run();

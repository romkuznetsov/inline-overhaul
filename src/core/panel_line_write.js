"use strict";

/**
 * Как записать вид панели, ничего не удаляя из строки человека.
 *
 * **Зачем.** Пока панель открыта, её полоса встаёт **на место** значений: они
 * из документа на время выбора исчезают. Ступень истории, которая эти значения
 * когда-то написала, переносится через их удаление и схлопывается — и `Ctrl+Z`
 * после сессии возвращает состояние, которого на строке никогда не было
 * (У-160, замечание заказчика 2026-09-12). Пометка «мимо истории» обещает не
 * заводить **свою** ступень, и только это (У-97).
 *
 * **Решение заказчика 2026-09-13:** полоса встаёт **рядом**, а не вместо.
 * Документ получает только вставку; всё, что полоса собой закрывает, остаётся
 * в тексте и прячется оформлением. Форма измерена стендом до правки:
 * `tools/undo_bench.js` дал ноль лишних состояний в обоих своих случаях против
 * четырёх и пяти у прежней формы.
 *
 * **Правило здесь одно, и оно не про панель.** Что панель показывает, решает
 * `renderControlLine` — он не тронут. Здесь решается другое: как превратить
 * «было так, а показать надо вот так» в запись **без удаления**. Ответ читается
 * из самих двух строк: чего нет в строке человека — вставляется, чего нет в
 * виде панели — прячется.
 *
 * **У плана два свойства, и проверяются они здесь же, а не набором.** Убрать
 * спрятанное — получить ровно тот вид, что нарисовал движок. Убрать
 * вставленное — получить строку человека знак в знак. Не сошлось — плана нет,
 * и зовущий пишет по-старому: вид человек видит сейчас, а история отмен
 * понадобится ему потом. Свой разборщик объявляет правило и врёт молча (У-96),
 * а этот ещё и решает, что человек увидит.
 */

/**
 * Строка словами: кусок без пробелов вместе с пробелами перед ним.
 *
 * По словам, а не по знакам, нарочно: знаковое сравнение сводит `||` полосы и
 * `|` соседнего значения в один общий кусок и рвёт вставку пополам. Склейка
 * слов обратно даёт ту же строку знак в знак — это и делает план проверяемым.
 */
function splitWords(text) {
  const out = [];
  const src = String(text == null ? "" : text);
  let i = 0;
  while (i < src.length) {
    let j = i;
    while (j < src.length && /\s/.test(src[j])) j += 1;
    while (j < src.length && !/\s/.test(src[j])) j += 1;
    out.push(src.slice(i, j));
    i = j;
  }
  return out;
}

/**
 * Наибольшая общая подпоследовательность слов: сетка на середине.
 *
 * Считается она произведением длин, и на очень длинной строке это и есть то
 * место, где панель теряет время (`Р-12`). Профиль V8 на строке в 20 000
 * знаков: **1009 мс** против 13 мс на строке в 2 000 — длина выросла в десять
 * раз, цена в восемьдесят. Сетка там 3 300 × 3 300 клеток, и половину времени
 * рядом отнимает сборщик мусора.
 *
 * **Совпавшие начало и конец в сетку не попадают.** Панель вставляет свою
 * полосу в середину, а слова слева и справа от неё те же самые: при совпадении
 * первых слов есть оптимальная подпоследовательность, которая с этой пары
 * начинается, — то же верно и для последних. Отрезав их, мы не теряем ни одной
 * пары, а сетка считается только по остатку.
 *
 * **Расхождение измерено до правки и равно нулю.** 4 737 настоящих пар «строка
 * человека / вид панели», записанных с обхода строки (обе дороги, все Fields,
 * оба вида разделителей) и с пробы на прочность: планы совпали целиком, поле в
 * поле. У меры контроль: порченая версия обязана дать расхождение на тех же
 * парах.
 */
function commonPairs(a, b) {
  const n = a.length;
  const m = b.length;

  let head = 0;
  while (head < n && head < m && a[head] === b[head]) head += 1;
  let tail = 0;
  while (tail < n - head && tail < m - head && a[n - 1 - tail] === b[m - 1 - tail]) tail += 1;

  const pairs = [];
  for (let k = 0; k < head; k++) pairs.push([k, k]);

  const ni = n - tail - head;
  const mi = m - tail - head;
  if (ni > 0 && mi > 0) {
    const grid = [];
    for (let i = 0; i <= ni; i++) grid.push(new Array(mi + 1).fill(0));
    for (let i = ni - 1; i >= 0; i--) {
      for (let j = mi - 1; j >= 0; j--) {
        grid[i][j] = a[head + i] === b[head + j]
          ? grid[i + 1][j + 1] + 1
          : Math.max(grid[i + 1][j], grid[i][j + 1]);
      }
    }
    let i = 0;
    let j = 0;
    while (i < ni && j < mi) {
      if (a[head + i] === b[head + j]) { pairs.push([head + i, head + j]); i += 1; j += 1; }
      else if (grid[i + 1][j] >= grid[i][j + 1]) i += 1;
      else j += 1;
    }
  }

  for (let k = 0; k < tail; k++) pairs.push([n - tail + k, m - tail + k]);
  return pairs;
}

/** Собрать строку, выбросив перечисленные отрезки. */
function withoutRanges(text, ranges) {
  let out = "";
  let at = 0;
  for (const [from, to] of ranges) {
    out += text.slice(at, from);
    at = to;
  }
  return out + text.slice(at);
}

/**
 * План записи: что написать в строку и что на ней спрятать.
 *
 * Отрезки вставленного отдаются наружу нарочно: **убирать вставку надо ровно
 * теми же отрезками**, а не общим различием двух строк. Различие по общему
 * началу и концу режет строку одним куском посередине — и уносит вместе со
 * вставкой то, что панель показала чужим же токеном. На стенде это стоило пяти
 * лишних состояний ровно в том случае, где значение есть и в своём Block.
 *
 * @param {string} originalLine строка человека, как она лежит в заметке
 * @param {string} controlLine вид панели, как его нарисовал движок
 * @returns {{text: string, hidden: Array<Array<number>>, inserted: Array<Array<number>>}|null}
 *   план либо `null`, если свойства не сошлись — тогда зовущий пишет по-старому
 */
function planPanelLineWrite(originalLine, controlLine) {
  const src = String(originalLine == null ? "" : originalLine);
  const view = String(controlLine == null ? "" : controlLine);
  if (!view) return null;

  const a = splitWords(src);
  const b = splitWords(view);
  const pairs = commonPairs(a, b);

  let text = "";
  const hidden = [];
  const inserted = [];
  let ai = 0;
  let bi = 0;
  const push = (list, from, to) => {
    if (to <= from) return;
    const last = list.length ? list[list.length - 1] : null;
    if (last && last[1] === from) last[1] = to;
    else list.push([from, to]);
  };
  const takeFromSrc = (untilWord) => {
    while (ai < untilWord) {
      const at = text.length;
      text += a[ai];
      push(hidden, at, text.length);
      ai += 1;
    }
  };
  const takeFromView = (untilWord) => {
    while (bi < untilWord) {
      const at = text.length;
      text += b[bi];
      push(inserted, at, text.length);
      bi += 1;
    }
  };

  for (const pair of pairs) {
    takeFromSrc(pair[0]);
    takeFromView(pair[1]);
    text += a[ai];
    ai += 1;
    bi += 1;
  }
  takeFromSrc(a.length);
  takeFromView(b.length);

  /*
   * **Граница вставки не режет чужую ступень.**
   *
   * Слово здесь несёт пробел **перед** собой, поэтому вставка начинается на
   * пробеле, который в строке человека уже стоял, — и снятие вставки этот
   * пробел уносит, разрезая ступень, которая его написала. На стенде это
   * стоило четырёх лишних состояний ровно там, где без нормализации их было
   * ноль: строка начинается со знака списка, и `- ` пришло одной ступенью.
   *
   * Пробел свой от чужого здесь не отличить, а двигать границу можно: пока
   * отрезок начинается тем же знаком, каким начинается текст сразу за ним,
   * сдвиг на знак вправо ничего не меняет в результате и уводит границу с
   * чужого пробела на наш.
   */
  for (const range of inserted) {
    while (range[1] < text.length && text[range[0]] === text[range[1]]
      && /\s/.test(text[range[0]])) {
      range[0] += 1;
      range[1] += 1;
    }
  }

  if (withoutRanges(text, hidden) !== view) return null;
  if (withoutRanges(text, inserted) !== src) return null;

  /*
   * Те же вставки, но в столбцах **строки человека**: ими панель и пишет.
   * Писать различием двух своих видов нельзя — между кусками полосы стоит
   * значение, которое человек написал сам, и различие уносит его вместе с
   * прежним видом. Отсюда порядок: снять прежнюю вставку точными отрезками,
   * поставить новую точными вставками, и ни в одном из двух шагов не тронуть
   * ни знака человека.
   */
  const insertAt = [];
  let before = 0;
  let cut = 0;
  for (const range of inserted) {
    before = range[0] - cut;
    insertAt.push([before, text.slice(range[0], range[1])]);
    cut += range[1] - range[0];
  }
  return { text, hidden, inserted, insertAt };
}

module.exports = { planPanelLineWrite, splitWords, withoutRanges };
